$PixelData = New-Object byte[] 2048

Function Set-Char {
    Param( $index, $bytes )
    For ( $i = 0 ; $i -lt 8 ; $i++ ) {
        $PixelData[ ( $index * 8 ) + $i ] = $bytes[ $i ]
    }
}

